/**
 * Step 3: Generate the two nginx map files.
 *
 *   1. legacy-to-new.map        help.ovhcloud.com/csm/* → docs.ovhcloud.com
 *                               Built from legacy-urls.csv (Step 1 output)
 *                               with prod-redirections.map renames merged in:
 *                               when a rename source has a home-fallback in
 *                               CSV but its rename target maps to a specific
 *                               page, the source is upgraded.
 *
 *   2. legacy-docs-to-new.map   docs.ovh.com/* → docs.ovhcloud.com
 *                               Built from prod-redirections_docs.map crossed
 *                               with the Step 1 CSV map (Step 2 output).
 *
 * All 301s. Targets are clean (no trailing slash, no .html, no query).
 *
 * Source patterns match against nginx `$uri` (path only, query stripped).
 * The companion nginx conf must use `map $uri $...` rather than
 * `map $request_uri $...` so that:
 *   - CSM URLs with any `?id=...` query land on the same redirect
 *   - tracking parameters (?utm_source=...) don't break matching
 *
 * A third map file (csm-to-new.map for residual CSM-internal renames not in
 * legacy-urls.csv) was considered but proven empty by construction: the
 * pre-pass merges every relevant rename into legacy-to-new.map.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const DOCS = 'https://docs.ovhcloud.com';

const csmMap = JSON.parse(
  readFileSync('/tmp/csm-slug-to-redirect.json', 'utf8'),
);
const legacyDocs = JSON.parse(readFileSync('/tmp/legacy-docs.json', 'utf8'));

function nginxEscape(s) {
  return s.replace(/[.*+?^$(){}|[\]\\]/g, '\\$&');
}

function entryTarget({ locale, docPath }) {
  return docPath ? `${DOCS}/${locale}/${docPath}` : `${DOCS}/${locale}/`;
}

// ────────────────────────────────────────────────────────────
// Pre-pass: merge prod-redirections.map renames into csmMap when they
// provide a BETTER target than the CSV (CSV says home-fallback, rename
// gives specific page). This prevents the same CSM slug from appearing
// in both legacy-to-new.map (with home) and csm-to-new.map (with page).
// ────────────────────────────────────────────────────────────
{
  const csmContent = readFileSync('redirections/prod-redirections.map', 'utf8');
  let upgraded = 0;
  for (const line of csmContent.split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const m = line.match(/^(\S+)\s+(\S+);?$/);
    if (!m) continue;
    const sm = m[1].match(/^\/csm\/([^?\s]+)/);
    const dm = m[2].match(/csm\/([^?\s]+)/);
    if (!sm || !dm) continue;
    const srcKey = sm[1],
      destKey = dm[1];
    const renameTarget = csmMap[destKey];
    if (!renameTarget?.docPath) continue; // rename target not specific

    const current = csmMap[srcKey];
    if (current && !current.docPath) {
      // current is home-fallback; upgrade to rename's specific target
      csmMap[srcKey] = renameTarget;
      upgraded++;
    } else if (!current) {
      // not in CSV at all — add it
      csmMap[srcKey] = renameTarget;
      upgraded++;
    }
  }
  console.log(
    `  Pre-pass: ${upgraded} legacy-to-new entries upgraded via rename data`,
  );
}

// ────────────────────────────────────────────────────────────
// 1. legacy-to-new.map (from CSV — direct help.ovhcloud.com → new docs)
// ────────────────────────────────────────────────────────────
{
  const entries = Object.entries(csmMap);
  entries.sort((a, b) => b[0].length - a[0].length);

  const lines = [
    `# help.ovhcloud.com/csm/* → docs.ovhcloud.com`,
    `# Generated by scripts/build-redirections-step3.mjs from legacy-urls.csv`,
    `# Entries: ${entries.length}`,
    `# Use with nginx \`map $uri\` directive on help.ovhcloud.com, response code 301.`,
    '',
  ];
  for (const [csmSlug, info] of entries) {
    lines.push(`~^/csm/${nginxEscape(csmSlug)}$  ${entryTarget(info)};`);
  }
  writeFileSync('redirections/legacy-to-new.map', `${lines.join('\n')}\n`);
  console.log(`  legacy-to-new.map:      ${entries.length} entries`);
}

// ────────────────────────────────────────────────────────────
// 2. legacy-docs-to-new.map (docs.ovh.com → new docs)
// ────────────────────────────────────────────────────────────
{
  const lines = [
    `# docs.ovh.com → docs.ovhcloud.com`,
    `# Generated by scripts/build-redirections-step3.mjs from prod-redirections_docs.map`,
    `# Entries: ${legacyDocs.length}`,
    `# Use with nginx \`map $uri\` directive on docs.ovh.com, response code 301.`,
    `# Unmigrated pages fall back to the locale home page (per project policy).`,
    '',
  ];
  const sorted = [...legacyDocs].sort(
    (a, b) => b.source.length - a.source.length,
  );
  for (const e of sorted) {
    // Tolerate optional trailing slash so both /fr/foo and /fr/foo/ match
    lines.push(`~^${nginxEscape(e.source)}/?$  ${e.target};`);
  }
  writeFileSync('redirections/legacy-docs-to-new.map', `${lines.join('\n')}\n`);
  console.log(`  legacy-docs-to-new.map: ${legacyDocs.length} entries`);
}

// Note: a third map file (`csm-to-new.map`) for residual CSM-internal renames
// not present in legacy-urls.csv was considered, but the pre-pass above
// merges every relevant rename into legacy-to-new.map. The residual file
// would be empty by construction, so it isn't generated.

console.log('\nDone.');
